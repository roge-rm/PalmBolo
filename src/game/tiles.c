const TileDef *tile_def(uint8_t i)
{
	return &kTiles[i < TILE_COUNT ? i : TILE_DEEP_SEA];
}

uint8_t tile_for_terrain(uint8_t terrain)
{
	if (terrain == 255)
		return TILE_DEEP_SEA;
	if (terrain >= TILE_COUNT)
		return TILE_DEEP_SEA;
	return terrain;
}

uint8_t tile_mono(const uint8_t rgb[3])
{
	return (rgb[0] * 3 + rgb[1] * 6 + rgb[2]) / 10 >= 128 ? 0 : 1;
}

uint8_t tile_mine_mark(uint8_t px, uint8_t py)
{
	if (px < 2 || px > 5 || py < 2 || py > 5)
		return 0;
	if (px >= 3 && px <= 4 && py >= 3 && py <= 4)
		return 2;
	return 1;
}
